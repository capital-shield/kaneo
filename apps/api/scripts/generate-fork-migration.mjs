#!/usr/bin/env node
/**
 * Regenerate the fork's schema migration.
 *
 * drizzle-kit can only diff against one snapshot chain, and ours has to stay
 * byte-identical to upstream. So this borrows the upstream chain: it runs
 * drizzle-kit generate, lifts the SQL it produced into drizzle-fork/, then puts
 * the upstream chain back exactly as it was.
 *
 * The diff is always taken against upstream's current tip, so the output is
 * always the *complete* set of columns the fork adds on top of upstream. That
 * is deliberate: rerun this after merging upstream and the file re-converges on
 * its own. It also means the file is rewritten in place and replayed, which is
 * why every statement is made idempotent.
 *
 * Data migrations (backfills and the like) do not belong here. Hand-write them
 * as later, higher-numbered files in drizzle-fork/; this script never touches
 * them, and only pushes their `when` forward to keep the journal ordered.
 *
 *   pnpm --filter @kaneo/api db:generate:fork
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const apiDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const upstreamDir = join(apiDir, "drizzle");
const forkDir = join(apiDir, "drizzle-fork");
const upstreamJournalPath = join(upstreamDir, "meta", "_journal.json");
const forkJournalPath = join(forkDir, "meta", "_journal.json");

const GENERATED_TAG = "0000_fork_schema";

const HEADER = `-- Generated by \`pnpm --filter @kaneo/api db:generate:fork\` — do not edit.
-- The complete set of schema changes this fork adds on top of upstream, as a
-- single converging migration. Rerun the script after merging upstream.
-- Statements are idempotent because this file is rewritten and replayed.

`;

const sqlFiles = (dir) =>
  new Set(readdirSync(dir).filter((f) => f.endsWith(".sql")));
const snapshotFiles = (dir) =>
  new Set(
    readdirSync(join(dir, "meta")).filter((f) => f.endsWith("_snapshot.json")),
  );

/** drizzle-kit does not emit existence guards; this chain is replayed, so add them. */
function makeIdempotent(sql) {
  const rewrites = [
    [/ADD COLUMN (?!IF NOT EXISTS)/g, "ADD COLUMN IF NOT EXISTS "],
    [/CREATE INDEX (?!IF NOT EXISTS)/g, "CREATE INDEX IF NOT EXISTS "],
    [
      /CREATE UNIQUE INDEX (?!IF NOT EXISTS)/g,
      "CREATE UNIQUE INDEX IF NOT EXISTS ",
    ],
    [/CREATE TABLE (?!IF NOT EXISTS)/g, "CREATE TABLE IF NOT EXISTS "],
  ];
  let guarded = sql;
  let count = 0;
  for (const [pattern, replacement] of rewrites) {
    guarded = guarded.replace(pattern, () => {
      count += 1;
      return replacement;
    });
  }
  return { sql: guarded.replace(/ {2,}"/g, ' "'), count };
}

const sqlBefore = sqlFiles(upstreamDir);
const snapshotsBefore = snapshotFiles(upstreamDir);
const upstreamJournalBefore = readFileSync(upstreamJournalPath, "utf8");

let generatedSql = "";
try {
  execFileSync("npx", ["drizzle-kit", "generate"], {
    cwd: apiDir,
    stdio: "inherit",
  });
} finally {
  const generated = [...sqlFiles(upstreamDir)].filter((f) => !sqlBefore.has(f));
  generatedSql = generated
    .map((file) => readFileSync(join(upstreamDir, file), "utf8"))
    .join("\n--> statement-breakpoint\n");

  // Always hand the upstream chain back untouched, even if generate failed.
  for (const file of generated) {
    rmSync(join(upstreamDir, file));
  }
  for (const file of snapshotFiles(upstreamDir)) {
    if (!snapshotsBefore.has(file)) {
      rmSync(join(upstreamDir, "meta", file));
    }
  }
  writeFileSync(upstreamJournalPath, upstreamJournalBefore);
}

if (generatedSql.trim() === "") {
  console.log(
    "\nThe fork adds nothing to upstream's schema — nothing written.",
  );
  process.exit(0);
}

const { sql, count } = makeIdempotent(generatedSql.trim());
writeFileSync(join(forkDir, `${GENERATED_TAG}.sql`), `${HEADER}${sql}\n`);

// Every entry must have a strictly increasing `when`: the migrator walks the
// journal in order against a single high-water mark, so an out-of-order entry
// would be skipped outright on a fresh database.
const journal = JSON.parse(readFileSync(forkJournalPath, "utf8"));
let when = Date.now();
for (const entry of journal.entries) {
  entry.when = when;
  when += 1;
}
writeFileSync(forkJournalPath, `${JSON.stringify(journal, null, "\t")}\n`);

console.log(
  `\n✅ Wrote drizzle-fork/${GENERATED_TAG}.sql (${count} statements guarded)`,
);
console.log("   Review it, then verify with pnpm test:integration.");
